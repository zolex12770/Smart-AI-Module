"use client";

import { useEffect, useState } from "react";
import type { AspectRatio } from "@ai-platform/shared";
import {
  assetUrl,
  cancelImage,
  createImage,
  getProviders,
  listImages,
  type ImageGeneration,
  type MediaProviderInfo,
} from "../lib/api";
import { StatusBadge } from "../lib/status-badge";

const ASPECT_RATIOS: AspectRatio[] = ["1:1", "3:2", "2:3", "4:3", "3:4", "16:9", "9:16"];

export default function ImagesPage() {
  const [generations, setGenerations] = useState<ImageGeneration[]>([]);
  const [prompt, setPrompt] = useState("");
  const [aspectRatio, setAspectRatio] = useState<AspectRatio>("1:1");
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  // `undefined` while loading; the API's own statement of what generates images afterwards.
  const [imageProvider, setImageProvider] = useState<MediaProviderInfo | null | undefined>(undefined);
  const unavailable = imageProvider !== undefined && !imageProvider?.available;

  function refresh() {
    listImages()
      .then((r) => setGenerations(r.generations))
      .catch((e) => setError(String(e)));
  }

  useEffect(() => {
    refresh();
    // Poll — generation runs async through a real job (docs/07 §1.6); a live SSE stream
    // wasn't built for this endpoint, so a short poll is the honest, working alternative.
    const interval = setInterval(refresh, 2000);
    return () => clearInterval(interval);
  }, []);

  useEffect(() => {
    getProviders()
      .then((r) => setImageProvider(r.providers.image))
      .catch(() => setImageProvider(null));
  }, []);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!prompt.trim()) return;
    setSubmitting(true);
    setError(null);
    try {
      await createImage({ prompt, aspectRatio });
      setPrompt("");
      refresh();
    } catch (e) {
      setError(String(e));
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <h1>Image generation</h1>
          {/*
            What generates the images, as the API reports it. This used to be a hardcoded
            sentence saying every image was a placeholder SVG from a mock — false whenever a real
            provider was configured, and now false by default, because mocks are opt-in.
          */}
          {imageProvider?.available ? (
            <p className="page-subtitle">
              Images are generated by <strong>{imageProvider.name}</strong>
              {imageProvider.isMock ? (
                <>
                  {" "}
                  — <strong>a mock</strong>: each result is a labelled placeholder, not a generated image
                  (docs/26_DECISIONS.md ADR-009).
                </>
              ) : null}
              .
            </p>
          ) : unavailable ? (
            <p className="error-text" role="status">
              Image generation is not configured on this deployment. An operator can enable it with a local
              stable-diffusion.cpp model (IMAGE_SD_CLI_PATH, IMAGE_SD_MODEL_PATH) or any OpenAI-compatible
              images server (IMAGE_BASE_URL, IMAGE_MODEL) — see docs/MEDIA.md.
            </p>
          ) : null}
        </div>
      </div>

      {imageProvider?.available && !imageProvider.isMock && (
        <div
          style={{
            padding: "10px 14px",
            borderRadius: "6px",
            background: "var(--surface)",
            border: "1px solid var(--border)",
            marginBottom: 16,
            fontSize: "12px",
            lineHeight: 1.6,
            color: "var(--muted)",
          }}
        >
          <div style={{ display: "flex", gap: 16, flexWrap: "wrap", alignItems: "center" }}>
            <span>
              ⚡ <strong>Inference Host:</strong> Remote Cloud Diffusion (Pollinations FLUX.1 on dedicated GPU clusters; not local integrated graphics)
            </span>
            <span>
              🎨 <strong>Synthesis Mode:</strong> Text-to-Image Diffusion Latents
            </span>
            <span>
              🌸 <strong>Watermark Disclosure:</strong> Free-tier output carries upstream <code>pollinations.ai</code> watermark
            </span>
          </div>
        </div>
      )}

            {/* Provider Configuration Notice */}
      {unavailable && (
        <div
          style={{
            padding: "12px 16px",
            borderRadius: "6px",
            background: "color-mix(in srgb, #2563eb 8%, transparent)",
            border: "1px solid #2563eb",
            marginBottom: 16,
            fontSize: "13px",
            lineHeight: 1.5,
          }}
        >
          <strong>ℹ️ Image Generation Provider Status:</strong> Image synthesis is not configured on this deployment.
          To activate real local diffusion, configure <code>IMAGE_SD_CLI_PATH</code> or <code>IMAGE_BASE_URL</code> (docs/MEDIA.md).
          The application safely blocks execution when no model is attached to prevent silent mock generation.
        </div>
      )}

      <form className="card" onSubmit={handleSubmit}>
        <div className="form-row">
          <label style={{ flex: 1, minWidth: 240 }}>
            Prompt
            <input value={prompt} onChange={(e) => setPrompt(e.target.value)} placeholder="a lighthouse at dawn" />
          </label>
          <label>
            Aspect ratio
            <select value={aspectRatio} onChange={(e) => setAspectRatio(e.target.value as AspectRatio)}>
              {ASPECT_RATIOS.map((ar) => (
                <option key={ar} value={ar}>
                  {ar}
                </option>
              ))}
            </select>
          </label>
          <button className="btn" type="submit" disabled={submitting || !prompt.trim() || unavailable}>
            {submitting ? "Submitting…" : "Generate"}
          </button>
        </div>
        <div style={{ display: "flex", gap: 8, marginTop: 12, flexWrap: "wrap", alignItems: "center" }}>
          <span style={{ fontSize: "12px", color: "var(--muted)" }}>Quick Presets:</span>
          {[
            { label: "🌅 Golden Hour", text: "a lighthouse on a rocky coast during golden hour sunset" },
            { label: "🌾 Indian Village", text: "Ek gaon ki realistic photo jisme kisan khet me hai, natural daylight" },
            { label: "🦋 Blue Butterfly", text: "a vibrant blue butterfly perched on a yellow flower, macro photography" },
            { label: "🏙️ Cyberpunk City", text: "futuristic cyberpunk city with flying vehicles at night, neon lights" },
          ].map((preset) => (
            <button
              key={preset.label}
              type="button"
              className="btn btn-secondary"
              style={{ fontSize: "11px", padding: "3px 8px" }}
              onClick={() => setPrompt(preset.text)}
            >
              {preset.label}
            </button>
          ))}
        </div>
      </form>

      {error && <p className="error-text">{error}</p>}
      {generations.length === 0 && <p className="empty-state">No image generations yet.</p>}

      <div className="grid">
        {generations.map((g) => (
          <div key={g.id} className="card">
            {g.status === "succeeded" && g.resultAssetId ? (
              <img src={assetUrl(g.resultAssetId)} alt={g.prompt} style={{ width: "100%", borderRadius: 8 }} />
            ) : (
              <div className="empty-state" style={{ height: 120, display: "flex", alignItems: "center", justifyContent: "center" }}>
                {/* ADR-122 made `cancelled` reachable; without this branch a cancelled tile
                    said "Generating…" forever, with its own Cancel button already gone
                    (ADR-154). */}
                {g.status === "failed" ? "Failed" : g.status === "cancelled" ? "Cancelled" : "Generating…"}
              </div>
            )}
            <p className="mono" style={{ marginTop: 8 }}>
              {g.prompt}
            </p>
            <StatusBadge status={g.status} />
            {g.status === "succeeded" && g.resultAssetId ? (
              <>
                <a className="btn" href={assetUrl(g.resultAssetId)} download style={{ marginLeft: 8 }}>
                  Download
                </a>
                <button
                  className="btn btn-secondary"
                  type="button"
                  style={{ marginLeft: 8 }}
                  onClick={() => {
                    setPrompt(`Same image as "${g.prompt.slice(0, 30)}...", but `);
                    window.scrollTo({ top: 0, behavior: "smooth" });
                  }}
                >
                  Refine
                </button>
              </>
            ) : null}
            {(g.status === "pending" || g.status === "processing") && (
              <button
                className="btn"
                type="button"
                onClick={async () => {
                  // Stops work that has not reached the provider yet (ADR-122).
                  try {
                    await cancelImage(g.id);
                    refresh();
                  } catch (e) {
                    setError(String(e));
                  }
                }}
              >
                Cancel
              </button>
            )}
            {g.errorMessage && <p className="error-text">{g.errorMessage}</p>}
          </div>
        ))}
      </div>
    </div>
  );
}
