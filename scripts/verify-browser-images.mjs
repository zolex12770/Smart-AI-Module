import { chromium } from "playwright";
import fs from "fs";
import path from "path";
import { execSync } from "child_process";

const ARTIFACT_DIR = "C:/Users/SAURABH KUMAR/.gemini/antigravity/brain/ab308118-6248-4511-b0d0-542a264329d5";

async function main() {
  console.log("=== BROWSER E2E VERIFICATION: PROMPT-TO-IMAGE RECOVERY ===");

  const browser = await chromium.launch({
    headless: true,
    channel: "chrome",
    args: ["--no-sandbox", "--disable-setuid-sandbox"],
  });

  const context = await browser.newContext({
    viewport: { width: 1280, height: 900 },
  });

  const page = await context.newPage();

  try {
    // 1. Authenticate
    console.log("[1/6] Authenticating via One-Click Sign In...");
    await page.goto("http://localhost:3000/login", { waitUntil: "networkidle", timeout: 25000 });
    const oneClickBtn = page.locator('button:has-text("One-Click Sign In")');
    await oneClickBtn.waitFor({ state: "visible", timeout: 10000 });
    await oneClickBtn.click();
    await page.waitForURL((url) => !url.pathname.includes("/login"), { timeout: 15000 });
    console.log("✓ Authenticated. Current URL:", page.url());

    // 2. Navigate to /images
    console.log("[2/6] Navigating to http://localhost:3000/images...");
    await page.goto("http://localhost:3000/images", { waitUntil: "networkidle", timeout: 25000 });

    // 3. Inspect Provider Status Display
    console.log("[3/6] Verifying image provider display...");
    await page.waitForSelector(".page-subtitle", { timeout: 15000 });
    const subtitle = (await page.locator(".page-subtitle").textContent()) || "";
    console.log("  Provider subtitle:", subtitle.trim());

    if (!subtitle.includes("flux-diffusion")) {
      throw new Error(`Expected provider name 'flux-diffusion' in subtitle, got: "${subtitle}"`);
    }
    if (subtitle.includes("a mock")) {
      throw new Error(`Provider subtitle incorrectly claims to be a mock: "${subtitle}"`);
    }

    const warningVisible = await page.locator("text=Image Generation Provider Status").isVisible();
    console.log("  Configuration warning banner visible:", warningVisible);
    if (warningVisible) {
      throw new Error("Provider warning banner should NOT be visible when flux-diffusion is active!");
    }
    console.log("✓ Provider display verified: 'Images are generated by flux-diffusion.' (isMock: false)");

    // 4. Fill Prompt & Submit Generation
    const promptText = "A lighthouse at dawn on a rocky coast";
    console.log(`[4/6] Submitting prompt: "${promptText}"...`);
    const promptInput = page.locator('input[placeholder="a lighthouse at dawn"]');
    await promptInput.fill(promptText);

    const generateBtn = page.locator('button:has-text("Generate")');
    await generateBtn.click();
    console.log("✓ Generate clicked.");

    // 5. Wait for Generation Completion in Gallery
    console.log("[5/6] Waiting for generation completion in gallery...");
    const card = page.locator(`.grid .card:has-text("${promptText}")`).first();
    await card.waitFor({ state: "visible", timeout: 15000 });

    // Poll until the card has an <img> tag or succeeded badge
    const successImg = card.locator("img");
    await successImg.waitFor({ state: "visible", timeout: 120000 });
    console.log("✓ Generated image element is visible in gallery!");

    const imgSrc = await successImg.getAttribute("src");
    console.log("  Image src:", imgSrc);
    if (!imgSrc || !imgSrc.includes("/api/v1/assets/")) {
      throw new Error(`Expected image src to point to /api/v1/assets/, got: ${imgSrc}`);
    }

    // Verify Download Button
    const downloadBtn = card.locator('a:has-text("Download")');
    const downloadHref = await downloadBtn.getAttribute("href");
    console.log("  Download href:", downloadHref);
    if (!downloadHref || !downloadHref.includes("/api/v1/assets/")) {
      throw new Error("Download button href does not point to asset!");
    }

    // Download the rendered image from browser and inspect with OpenCV
    const cookies = await context.cookies();
    const cookieHeader = cookies.map((c) => `${c.name}=${c.value}`).join("; ");
    const fullImgUrl = imgSrc.startsWith("http") ? imgSrc : `http://localhost:3000${imgSrc}`;
    const imgRes = await fetch(fullImgUrl, { headers: { Cookie: cookieHeader } });
    const imgBuffer = Buffer.from(await imgRes.arrayBuffer());

    const browserImgPath = path.join(ARTIFACT_DIR, "browser_lighthouse_dawn.png");
    fs.writeFileSync(browserImgPath, imgBuffer);
    console.log(`✓ Saved browser image to ${browserImgPath} (${imgBuffer.length} bytes)`);

    // Run CV analysis
    const cvOutput = execSync(`python scripts/lib/analyze_image.py "${browserImgPath}"`, { encoding: "utf-8" });
    const metrics = JSON.parse(cvOutput.trim());
    console.log("  CV Analysis of browser image:", metrics);

    if (metrics.std_dev < 30 || metrics.edge_pixels < 2000) {
      throw new Error("Image appears to be flat or blank!");
    }

    // 6. Verify Reload Persistence
    console.log("[6/6] Verifying reload persistence...");
    await page.reload({ waitUntil: "networkidle" });
    await page.waitForSelector(".grid .card", { timeout: 15000 });
    const persistedCard = page.locator(`.grid .card:has-text("${promptText}")`).first();
    await persistedCard.waitFor({ state: "visible", timeout: 10000 });
    const persistedImg = persistedCard.locator("img");
    await persistedImg.waitFor({ state: "visible", timeout: 10000 });
    console.log("✓ Image generation successfully persisted across full browser reload!");

    // Capture Full Page Screenshot
    const screenshotPath = path.join(ARTIFACT_DIR, "browser_verified_images_flux.png");
    await page.screenshot({ path: screenshotPath, fullPage: true });
    console.log(`✓ Saved full-page verification screenshot to ${screenshotPath}`);

    console.log("\n=== BROWSER E2E VERIFICATION COMPLETED SUCCESSFULLY ===");
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error("FATAL ERROR in browser verification:", err);
  process.exit(1);
});
