#!/usr/bin/env node
/**
 * docs/ENVIRONMENT.md from the two env templates — the backend's (every key config.ts reads;
 * `backend/src/env-example.test.ts` holds it to that) and the frontend's.
 *
 * Each variable is documented where it is declared, by the comment block above it; this only
 * collects them into one table, so the reference cannot drift from the templates it is made of.
 * `node scripts/generate-env-docs.mjs --check` exits non-zero when the committed file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "docs/ENVIRONMENT.md");

function parse(file) {
  const lines = readFileSync(join(ROOT, file), "utf8").split(/\r?\n/);
  const rows = [];
  let section = "General";
  let comment = [];
  /** A comment above several keys with no blank line between them describes all of them. */
  let group = "";
  for (const raw of lines) {
    const line = raw.trim();
    const heading = /^#\s*-{2,}\s*(.+?)\s*-{2,}/.exec(line);
    if (heading) {
      section = heading[1];
      comment = [];
      continue;
    }
    const setting = /^#?\s*([A-Z][A-Z0-9_]+)=(.*)$/.exec(line);
    if (setting) {
      const [, key, rest] = setting;
      const inline = /\s#\s*(.*)$/.exec(rest);
      const value = rest.replace(/\s+#.*$/, "").trim();
      const own = [...comment, ...(inline ? [inline[1]] : [])].join(" ").replace(/\s+/g, " ").trim();
      if (comment.length) group = own;
      const purpose = own || group;
      if (!rows.some((r) => r.key === key)) {
        rows.push({ key, section, example: value, commented: line.startsWith("#"), purpose });
      }
      comment = [];
      continue;
    }
    if (line.startsWith("#")) {
      const text = line.replace(/^#+\s?/, "");
      if (/^-+$/.test(text)) continue;
      comment.push(text);
    } else if (line === "") {
      comment = [];
      group = "";
    }
  }
  return rows;
}

const escape = (s) => s.replace(/\|/g, "\\|");
function table(rows) {
  const out = [];
  let section = null;
  for (const row of rows) {
    if (row.section !== section) {
      section = row.section;
      out.push("", `### ${section}`, "", "| Variable | Template value | What it does |", "|---|---|---|");
    }
    const value = row.example === "" ? "*(empty)*" : `\`${escape(row.example)}\``;
    out.push(`| \`${row.key}\` | ${row.commented ? `unset (e.g. ${value})` : value} | ${escape(row.purpose || "See the template.")} |`);
  }
  return out.join("\n");
}

const backend = parse("backend/.env.example");
const frontend = parse("frontend/.env.example");
const doc = `# Environment variables

Generated by \`node scripts/generate-env-docs.mjs\` from \`backend/.env.example\` (${backend.length} variables — every key
\`backend/src/config.ts\` reads, enforced by \`backend/src/env-example.test.ts\`) and \`frontend/.env.example\`
(${frontend.length}). Edit the templates, not this file. "unset" means the template leaves it commented out, so the
default in \`config.ts\` applies.

## The five that decide what runs

| Setting | Variable | Default |
|---|---|---|
| FRONTEND_PORT | \`PORT\` for \`next dev\`/\`next start\` (\`npm run dev -- -p <port>\`) | 3000 |
| BACKEND_PORT | \`PORT\` (backend) | 8787 |
| DATABASE | \`DATABASE_URL\` (Postgres + pgvector); unset → embedded PGlite at \`DATABASE_DIR\` | PGlite, \`backend/data/pgdata\` |
| MODEL_RUNTIME | \`LLM_BASE_URL\` + \`LLM_MODEL\` (any OpenAI-compatible server), else Ollama auto-detected on 127.0.0.1:11434; or a hosted key (\`ANTHROPIC_API_KEY\`, \`OPENAI_API_KEY\`, \`GOOGLE_API_KEY\`) | auto-detect |
| MEDIA_RUNTIME | \`IMAGE_SD_CLI_PATH\` + \`IMAGE_SD_MODEL_PATH\` (images, and local video with ffmpeg), \`SPEECH_PROVIDER=piper\` + \`PIPER_PATH\` + \`PIPER_VOICE\` (speech), \`FFMPEG_PATH\` (video assembly) | none: each capability reports itself unavailable |

## Backend
${table(backend)}

## Frontend
${table(frontend)}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(TARGET, "utf8");
  if (current !== doc) {
    process.stderr.write("docs/ENVIRONMENT.md is stale: run node scripts/generate-env-docs.mjs\n");
    process.exit(1);
  }
  process.stdout.write("docs/ENVIRONMENT.md is current\n");
} else {
  writeFileSync(TARGET, doc);
  process.stdout.write(`docs/ENVIRONMENT.md: ${backend.length} backend + ${frontend.length} frontend variables\n`);
}
